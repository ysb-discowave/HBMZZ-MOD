package com.hbmzz.tile;

import net.minecraft.block.state.IBlockState;
import net.minecraft.tileentity.TileEntity;
import net.minecraft.util.math.BlockPos;
import net.minecraft.world.World;

/**
 * The block the status lamp is mounted in.
 *
 * <p>It holds nothing: the lamp's colour comes from the facility record on the
 * client, and its facing comes from the block state. The tile entity exists only
 * so the renderer has an object to key its geometry to - breaking the block
 * loses nothing, and there is nothing for it to lose.</p>
 */
public class TileEntityStatusLamp extends TileEntity {

    @Override
    public boolean shouldRefresh(World world, BlockPos pos, IBlockState oldState, IBlockState newState) {
        return oldState.getBlock() != newState.getBlock();
    }
}
