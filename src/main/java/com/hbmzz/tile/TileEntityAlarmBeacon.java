package com.hbmzz.tile;

import net.minecraft.block.state.IBlockState;
import net.minecraft.tileentity.TileEntity;
import net.minecraft.util.math.BlockPos;
import net.minecraft.world.World;

/**
 * The block the rotating alarm beacon is mounted in.
 *
 * <p>Like the status lamp it holds nothing: whether the beacon spins and what
 * colour it spins in are decided on the client from the facility record and the
 * configured safe level. The tile entity is only the renderer's anchor.</p>
 */
public class TileEntityAlarmBeacon extends TileEntity {

    @Override
    public boolean shouldRefresh(World world, BlockPos pos, IBlockState oldState, IBlockState newState) {
        return oldState.getBlock() != newState.getBlock();
    }
}
