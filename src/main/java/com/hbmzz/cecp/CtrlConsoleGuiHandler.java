package com.hbmzz.cecp;

import com.hbmzz.cecp.tile.TileEntityCtrlConsole;
import net.minecraft.entity.player.EntityPlayer;
import net.minecraft.tileentity.TileEntity;
import net.minecraft.util.math.BlockPos;
import net.minecraft.world.World;
import net.minecraftforge.fml.common.network.IGuiHandler;

/**
 * Routes the console's layout editor.
 *
 * <p>NTM: Cursed Edition registers this through its own {@code IGUIProvider}
 * interface on the tile entity; this mod has no such infrastructure, so the
 * same container/gui pair is wired through FML's plain gui handler with a single
 * id.</p>
 */
public class CtrlConsoleGuiHandler implements IGuiHandler {

    public static final int GUI_CONSOLE = 0;

    @Override
    public Object getServerGuiElement(int id, EntityPlayer player, World world, int x, int y, int z) {
        TileEntity te = world.getTileEntity(new BlockPos(x, y, z));
        if (te instanceof TileEntityCtrlConsole) {
            return new ContainerControlEdit(player.inventory, (TileEntityCtrlConsole) te);
        }
        return null;
    }

    @Override
    public Object getClientGuiElement(int id, EntityPlayer player, World world, int x, int y, int z) {
        TileEntity te = world.getTileEntity(new BlockPos(x, y, z));
        if (te instanceof TileEntityCtrlConsole) {
            return new GuiControlEdit(player.inventory, (TileEntityCtrlConsole) te);
        }
        return null;
    }
}
